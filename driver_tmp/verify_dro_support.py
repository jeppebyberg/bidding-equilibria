def _parse_profile(v: Any) -> list[float]:
    if isinstance(v, (list, np.ndarray)):
        return [float(x) for x in v]
    return [float(x) for x in ast.literal_eval(str(v))]


def _build_wind_profiles(
    df: pd.DataFrame,
    manager: ScenarioManager,
    N: int,
    T: int,
) -> dict[str, tuple[np.ndarray, float]]:
    """Return {gen_name: (profiles (N,T) in MW, P_W_max)} for all wind generators."""
    result: dict[str, tuple[np.ndarray, float]] = {}
    for g in manager.physical_generators:
        if not bool(g["is_wind"]):
            continue
        name = g["physical_name"]
        P_W_max = float(g["pmax"])
        blocks = [b for b in manager.blocks if b["physical_name"] == name and bool(b["is_wind"])]
        profiles = np.zeros((N, T), dtype=float)
        for b in blocks:
            col = f"{b['block_name']}_profile"
            if col not in df.columns:
                continue
            profiles += np.array(
                [_parse_profile(df.at[s, col]) for s in range(N)],
                dtype=float,
            )
        result[name] = (profiles, P_W_max)
    return result


