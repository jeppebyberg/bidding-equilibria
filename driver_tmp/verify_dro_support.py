def calibrate_support_coverage(
    manager: "ScenarioManager",
    regime_config_path: "str | Path",
    regime_set: str,
    regime_name: str,
    horizon: int,
    n_draws: int,
    seed: int,
    coverage_grid: "list[float]",
) -> dict:
    """Generate n_draws fresh scenarios with `seed`, compute whitened innovations and
    stationary level deviations, sweep coverage_grid,
    and return the smallest single coverage giving 0% rejection across ALL families.

    Returns:
        {
            "regime_name": str,
            "coverage": float | None,   # smallest 0%-rejection coverage; None if none clears
            "kappa": float | None,
            "binding_family": str,      # which family forced the choice
            "per_family_rejection": {family: {coverage: pct}},
            "n_draws": int, "seed": int,
        }
    """
    manager.base_case["time_steps"] = horizon

    calibration_config_path = _single_regime_calibration_config(
        regime_config_path=regime_config_path,
        regime_set=regime_set,
        regime_name=regime_name,
        n_draws=n_draws,
    )
    config_path_for_generation = calibration_config_path or Path(regime_config_path)
    config_set_for_generation = (
        "__support_coverage_calibration__"
        if calibration_config_path is not None
        else regime_set
    )

    try:
        raw = manager.create_scenario_set_from_regimes(
            regime_config_path=str(config_path_for_generation),
            regime_set=config_set_for_generation,
            seed=seed,
        )
    finally:
        if calibration_config_path is not None:
            calibration_config_path.unlink(missing_ok=True)
    df = raw["scenarios_df"]
    if "regime" in df.columns:
        df = df[df["regime"] == regime_name].reset_index(drop=True)
    if len(df) == 0:
        return {
            "regime_name": regime_name, "coverage": None, "kappa": None,
            "binding_family": "no_draws", "per_family_rejection": {}, "n_draws": 0, "seed": seed,
        }
    df = df.iloc[:n_draws].reset_index(drop=True)
    N = len(df)

    if N < n_draws:
        import warnings
        warnings.warn(
            f"calibrate_support_coverage: only {N} draws available for regime '{regime_name}' "
            f"(requested {n_draws}). Calibration may be under-powered.",
            stacklevel=2,
        )

    T = horizon
    mu_D = float(df.at[0, "mu_D"])
    sigma_D = float(df.at[0, "sigma_D"])
    rho_D = float(df.at[0, "rho_D"])
    mu_W = float(df.at[0, "mu_W"])
    sigma_W = float(df.at[0, "sigma_W"])
    rho_W = float(df.at[0, "rho_W"])
    peak_W = float(df.at[0, "peak_W"])
    D_ref = float(manager.base_case["demand"])

    demand_shape = ScenarioManager._build_demand_shape(T)
    wind_shape = ScenarioManager._build_wind_shape(T, peak_W)

    demand_profiles = np.array([_parse_profile(df.at[s, "demand_profile"]) for s in range(N)])
    wind_gen_data = _build_wind_profiles(df, manager, N, T)

    sigma_D_innov = D_ref * sigma_D
    sigma_bar_D = D_ref * sigma_D / np.sqrt(1.0 - rho_D ** 2)

    demand_xi = _demand_innovations(demand_profiles, demand_shape, mu_D, rho_D, D_ref)
    demand_level_dev = _demand_level_dev(demand_profiles, demand_shape, mu_D, D_ref)

    # Build family dict: {name: (deviations (N,T), sigma_scale)}
    families: dict[str, tuple[np.ndarray, float]] = {
        "demand_innov": (demand_xi, sigma_D_innov),
        "demand_level": (demand_level_dev, sigma_bar_D),
    }
    for name, (wp, cap) in wind_gen_data.items():
        xi_w = _wind_innovations(wp, wind_shape, mu_W, rho_W, cap)
        lvl_dev = _wind_level_dev(wp, wind_shape, mu_W, cap)
        families[f"wind_{name}_innov"] = (xi_w, cap * sigma_W)
        families[f"wind_{name}_level"] = (lvl_dev, cap * sigma_W / np.sqrt(1.0 - rho_W ** 2))

    # Sweep: per family, per coverage
    sorted_grid = sorted(coverage_grid)
    per_family_rejection: dict[str, dict[float, float]] = {}
    family_min_coverage: dict[str, float | None] = {}

    for family, (devs, sigma) in families.items():
        per_family_rejection[family] = {}
        first_zero: float | None = None
        for cov in sorted_grid:
            kappa = _ar1_kappa(T, cov)
            pct = _rejection_rate(devs, sigma, kappa) * 100.0
            per_family_rejection[family][cov] = round(pct, 4)
            if pct == 0.0 and first_zero is None:
                first_zero = cov
        family_min_coverage[family] = first_zero

    # Global coverage = max over families (so every family clears at this value).
    clearing = {f: c for f, c in family_min_coverage.items() if c is not None}
    if not clearing:
        return {
            "regime_name": regime_name, "coverage": None, "kappa": None,
            "binding_family": "none_clear",
            "per_family_rejection": per_family_rejection,
            "n_draws": N, "seed": seed,
        }

    global_cov = max(clearing.values())
    # Tie-break: pick the family name alphabetically for determinism.
    binding = min(f for f, c in clearing.items() if c == global_cov)
    global_kappa = _ar1_kappa(T, global_cov)

    return {
        "regime_name": regime_name,
        "coverage": global_cov,
        "kappa": global_kappa,
        "binding_family": binding,
        "per_family_rejection": per_family_rejection,
        "n_draws": N,
        "seed": seed,
    }


def _single_regime_calibration_config(
    regime_config_path: str | Path,
    regime_set: str,
    regime_name: str,
    n_draws: int,
) -> Path | None:
    """Create a temporary one-regime config with n_draws scenarios.

    ScenarioManager takes sample counts from YAML, so calibration needs a
    temporary regime set instead of trusting the possibly tiny DRO runtime set.
    """
    path = Path(regime_config_path)
    with path.open("r", encoding="utf-8") as file_handle:
        raw_config = yaml.safe_load(file_handle) or {}

    regime_sets = raw_config.get("regime_sets")
    if not isinstance(regime_sets, dict) or regime_set not in regime_sets:
        return None

    selected_set = dict(regime_sets[regime_set] or {})
    regimes = selected_set.get("regimes", []) or []
    selected_regime: dict[str, Any] | None = None
    for regime in regimes:
        regime_copy = dict(regime or {})
        if str(regime_copy.get("name")) == str(regime_name):
            regime_copy["n_scenarios"] = int(n_draws)
            selected_regime = regime_copy
            break
    if selected_regime is None:
        return None

    selected_set["regimes"] = [selected_regime]
    calibration_config = {
        key: value
        for key, value in raw_config.items()
        if key not in {"regime_sets", "default_regime_set"}
    }
    calibration_config["default_regime_set"] = "__support_coverage_calibration__"
    calibration_config["regime_sets"] = {
        "__support_coverage_calibration__": selected_set,
    }

    with tempfile.NamedTemporaryFile(
        "w",
        encoding="utf-8",
        suffix=".yaml",
        delete=False,
    ) as temp_file:
        yaml.safe_dump(calibration_config, temp_file, sort_keys=False)
        return Path(temp_file.name)


def print_support_calibration_report(report: dict) -> None:
    print("\n--- Support coverage calibration ---")
    print(
        f"  Regime: {report.get('regime_name')}  "
        f"N={report.get('n_draws')}  seed={report.get('seed')}"
    )
    print(
        f"  Selected coverage={report.get('coverage')}  "
        f"kappa={report.get('kappa')}  binding={report.get('binding_family')}"
    )
    per_family = report.get("per_family_rejection", {}) or {}
    for family in sorted(per_family):
        values = per_family[family]
        row = ", ".join(
            f"{float(cov):.5g}: {float(pct):.4g}%"
            for cov, pct in sorted(values.items(), key=lambda item: float(item[0]))
        )
        print(f"    {family:<22} {row}")


