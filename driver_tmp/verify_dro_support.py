def check_rejection_rates(
    demand_xi: np.ndarray,
    wind_xi_by_gen: dict[str, np.ndarray],
    sigma_D: float,
    sigma_W_by_gen: dict[str, float],
    T: int,
    chosen_coverage: float,
) -> None:
    print("\n  AR(1) innovation rejection rate vs. coverage:")
    print(f"  {'Coverage':>10}  {'kappa':>8}  {'Demand%':>10}  {'Wind% max':>12}")
    print("  " + "-" * 46)
    for cov in COVERAGE_GRID:
        kappa = _ar1_kappa(T, cov)
        d = _rejection_rate(demand_xi, sigma_D, kappa) * 100
        w = max(
            (_rejection_rate(xi, sigma_W_by_gen[g], kappa) * 100 for g, xi in wind_xi_by_gen.items()),
            default=float("nan"),
        )
        mark = " <-- chosen" if abs(cov - chosen_coverage) < 1e-9 else ""
        print(f"  {cov:>10.4f}  {kappa:>8.4f}  {d:>9.2f}%  {w:>11.2f}%{mark}")


