def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    manager = ScenarioManager(CASE)
    manager.base_case["time_steps"] = HORIZON

    if RUN_SUPPORT_COVERAGE_CALIBRATION:
        calibration_report = calibrate_support_coverage(
            manager=manager,
            regime_config_path=REGIME_CONFIG,
            regime_set=REGIME_SET,
            regime_name=REGIME_NAME,
            horizon=HORIZON,
            n_draws=CALIBRATION_N_DRAWS,
            seed=CALIBRATION_SEED,
            coverage_grid=COVERAGE_GRID,
        )
        print_support_calibration_report(calibration_report)
        SUPPORT_CALIBRATION_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        with SUPPORT_CALIBRATION_REPORT_PATH.open("w", encoding="utf-8") as file_handle:
            json.dump(calibration_report, file_handle, indent=2)
        print(f"  Calibration report saved: {SUPPORT_CALIBRATION_REPORT_PATH}")

    if EXISTING_SCENARIOS_CSV is not None and EXISTING_SCENARIOS_CSV.exists():
        print(f"\nLoading existing DRO scenarios from {EXISTING_SCENARIOS_CSV}")
        existing_df = pd.read_csv(EXISTING_SCENARIOS_CSV)
        if "regime" in existing_df.columns:
            existing_df = existing_df[existing_df["regime"] == REGIME_NAME].reset_index(drop=True)
        if len(existing_df) == 0:
            print(f"  No rows for regime '{REGIME_NAME}' — skipping existing-scenario check.")
        else:
            _run_all_checks(existing_df, manager, "existing DRO scenarios", OUTPUT_DIR)
    else:
        if EXISTING_SCENARIOS_CSV is not None:
            print(f"\nExisting-scenarios CSV not found: {EXISTING_SCENARIOS_CSV}")
        print("Skipping existing-scenario check.")

    print(f"\nGenerating {N_DRAWS} fresh draws (seed={VERIFY_SEED}) ...")
    raw = manager.create_scenario_set_from_regimes(
        regime_config_path=str(REGIME_CONFIG),
        regime_set=REGIME_SET,
        seed=VERIFY_SEED,
    )
    fresh_df = raw["scenarios_df"]
    if "regime" in fresh_df.columns:
        fresh_df = fresh_df[fresh_df["regime"] == REGIME_NAME].reset_index(drop=True)
    if len(fresh_df) == 0:
        print(f"No scenarios generated for regime '{REGIME_NAME}'. "
              f"Available: {raw['scenarios_df']['regime'].unique().tolist()}")
        return
    fresh_df = fresh_df.iloc[:N_DRAWS].reset_index(drop=True)
    _run_all_checks(fresh_df, manager, "fresh draws (unconstrained)", OUTPUT_DIR)


if __name__ == "__main__":
    main()
