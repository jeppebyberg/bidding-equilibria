def _run_all_checks(
    df: pd.DataFrame,
    manager: ScenarioManager,
    source_label: str,
    output_dir: Path,
) -> None:
    N = len(df)
    T = HORIZON
    mu_D = float(df.at[0, "mu_D"])
    sigma_D = float(df.at[0, "sigma_D"])
    rho_D = float(df.at[0, "rho_D"])
    mu_W = float(df.at[0, "mu_W"])
    sigma_W = float(df.at[0, "sigma_W"])
    rho_W = float(df.at[0, "rho_W"])
    peak_W = float(df.at[0, "peak_W"])
    D_ref = float(manager.base_case["demand"])

    demand_shape = ScenarioManager._build_demand_shape(T)
    wind_shape = ScenarioManager._build_wind_shape(T, peak_W)

    demand_profiles = np.array([_parse_profile(df.at[s, "demand_profile"]) for s in range(N)])
    wind_gen_data = _build_wind_profiles(df, manager, N, T)
    total_capacity = sum(float(g["pmax"]) for g in manager.physical_generators)

    sigma_D_innov = D_ref * sigma_D
    sigma_bar_D = D_ref * sigma_D / np.sqrt(1.0 - rho_D ** 2)  # stationary level std

    demand_xi = _demand_innovations(demand_profiles, demand_shape, mu_D, rho_D, D_ref)
    demand_level_dev = _demand_level_dev(demand_profiles, demand_shape, mu_D, D_ref)

    wind_xi_by_gen: dict[str, np.ndarray] = {}
    sigma_W_by_gen: dict[str, float] = {}
    wind_level_devs_by_gen: dict[str, np.ndarray] = {}
    sigma_bar_W_by_gen: dict[str, float] = {}
    for name, (wp, P_W_max) in wind_gen_data.items():
        wind_xi_by_gen[name] = _wind_innovations(wp, wind_shape, mu_W, rho_W, P_W_max)
        sigma_W_by_gen[name] = P_W_max * sigma_W
        wind_level_devs_by_gen[name] = _wind_level_dev(wp, wind_shape, mu_W, P_W_max)
        sigma_bar_W_by_gen[name] = P_W_max * sigma_W / np.sqrt(1.0 - rho_W ** 2)

    caps = [cap for _, (_, cap) in wind_gen_data.items()]
    sum_caps = float(sum(caps))
    cap_rms = float(np.sqrt(sum(c ** 2 for c in caps)))
    sigma_bar_W_scalar = sigma_W / np.sqrt(1.0 - rho_W ** 2)
    cap_rms_sigma_bar_W = cap_rms * sigma_bar_W_scalar
    sum_caps_sigma_bar_W = sum_caps * sigma_bar_W_scalar

    fleet_profiles: np.ndarray = sum(  # type: ignore[assignment]
        wp for wp, _ in wind_gen_data.values()
    )
    fleet_dev = fleet_profiles - sum_caps * mu_W * wind_shape[np.newaxis, :]

    kappa_chosen = _ar1_kappa(T, CHOSEN_COVERAGE)
    kappa_lvl = _ar1_kappa(T, CHOSEN_LEVEL_COVERAGE)
    kappa_fleet = _ar1_kappa(T, CHOSEN_FLEET_COVERAGE)

    print(f"\n{'=' * 60}")
    print(f"Source: {source_label}  (N={N}, regime='{REGIME_NAME}', T={T})")
    print(f"Regime: mu_D={mu_D}, sigma_D={sigma_D}, rho_D={rho_D}")
    print(f"        mu_W={mu_W}, sigma_W={sigma_W}, rho_W={rho_W}")
    print(f"{'=' * 60}")

    print("\n--- Check 1: Whitened innovations and stationary level deviations ---")
    check_innovations(demand_xi, sigma_D_innov, f"Demand innovations [{source_label}]", output_dir)
    check_innovations(demand_level_dev, sigma_bar_D, f"Demand level [{source_label}]", output_dir)
    for name, xi_w in wind_xi_by_gen.items():
        check_innovations(xi_w, sigma_W_by_gen[name],
                          f"Wind {name} innovations [{source_label}]", output_dir)
    for name, ldev in wind_level_devs_by_gen.items():
        check_innovations(ldev, sigma_bar_W_by_gen[name],
                          f"Wind {name} level [{source_label}]", output_dir)

    print("\n--- Check 2a: AR(1) innovation rejection rate sweep ---")
    check_rejection_rates(demand_xi, wind_xi_by_gen, sigma_D_innov,
                          sigma_W_by_gen, T, CHOSEN_COVERAGE)

    print("\n--- Check 2b: Stationary level band rejection rate sweep ---")
    check_level_rejection_rates(demand_level_dev, wind_level_devs_by_gen, sigma_bar_D,
                                sigma_bar_W_by_gen, T, CHOSEN_LEVEL_COVERAGE)

    print("\n--- Check 2c: Fleet aggregate band ---")
    check_fleet_stats(fleet_dev, cap_rms_sigma_bar_W, sum_caps_sigma_bar_W)
    check_fleet_rejection_rates(fleet_dev, cap_rms_sigma_bar_W, T, CHOSEN_FLEET_COVERAGE)

    print("\n--- Check 3: Sawtooth adversarial test ---")
    first_wind = next(iter(wind_gen_data.values()), None)
    P_W_max_saw = first_wind[1] if first_wind else 0.0
    check_sawtooth(
        demand_shape=demand_shape, wind_shape=wind_shape,
        D_ref=D_ref, mu_D=mu_D, sigma_D=sigma_D, rho_D=rho_D,
        P_W_max=P_W_max_saw, mu_W=mu_W, sigma_W=sigma_W, rho_W=rho_W,
        total_capacity=total_capacity, T=T, chosen_coverage=CHOSEN_COVERAGE,
    )

    print("\n--- Check 4: Innovation-stack and fleet-stack corner tests ---")
    check_innovation_stack(
        demand_shape=demand_shape,
        D_ref=D_ref, mu_D=mu_D, rho_D=rho_D,
        T=T, kappa_innov=kappa_chosen, kappa_lvl=kappa_lvl,
        sigma_D_innov=sigma_D_innov, sigma_bar_D=sigma_bar_D,
    )
    check_fleet_stack(
        wind_shape=wind_shape,
        mu_W=mu_W, sigma_W=sigma_W, rho_W=rho_W,
        wind_gen_data=wind_gen_data,
        T=T, kappa_innov=kappa_chosen, kappa_fleet=kappa_fleet,
        cap_rms_sigma_bar_W=cap_rms_sigma_bar_W,
    )

    print("\n--- Support set bounds plot ---")
    plot_support_set_bounds(
        demand_profiles=demand_profiles,
        wind_gen_data=wind_gen_data,
        demand_shape=demand_shape,
        wind_shape=wind_shape,
        D_ref=D_ref, mu_D=mu_D, sigma_D=sigma_D, rho_D=rho_D,
        mu_W=mu_W, sigma_W=sigma_W, rho_W=rho_W,
        T=T, kappa_ar1=kappa_chosen, kappa_lvl=kappa_lvl, kappa_fleet=kappa_fleet,
        output_dir=output_dir, source_label=source_label,
    )

    d_rej = _rejection_rate(demand_xi, sigma_D_innov, kappa_chosen) * 100
    w_rej = max(
        (_rejection_rate(xi, sigma_W_by_gen[g], kappa_chosen) * 100
         for g, xi in wind_xi_by_gen.items()),
        default=float("nan"),
    )
    d_lvl_rej = _rejection_rate(demand_level_dev, sigma_bar_D, kappa_lvl) * 100
    w_lvl_rej = max(
        (_rejection_rate(dev, sigma_bar_W_by_gen[g], kappa_lvl) * 100
         for g, dev in wind_level_devs_by_gen.items()),
        default=float("nan"),
    )
    f_rej = _rejection_rate(fleet_dev, cap_rms_sigma_bar_W, kappa_fleet) * 100
    print(f"\n--- Summary [{source_label}] ---")
    print(f"  AR(1) innovations:   coverage={CHOSEN_COVERAGE}  kappa={kappa_chosen:.4f}")
    print(f"    Demand: {d_rej:.2f}%  Wind (max): {w_rej:.2f}%  (target 0%)")
    print(f"  Level band:          coverage={CHOSEN_LEVEL_COVERAGE}  kappa={kappa_lvl:.4f}")
