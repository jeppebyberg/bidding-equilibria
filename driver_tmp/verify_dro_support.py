def _demand_innovations(
    demand_profiles: np.ndarray,
    demand_shape: np.ndarray,
    mu_D: float,
    rho_D: float,
    D_ref: float,
) -> np.ndarray:
    """Whitened demand innovations (N, T).  Expected ~ N(0, (D_ref*sigma_D)^2)."""
    N, T = demand_profiles.shape
    xi = np.zeros((N, T), dtype=float)
    xi[:, 0] = demand_profiles[:, 0] - D_ref * mu_D * demand_shape[0]
    if T > 1:
        ref = D_ref * mu_D * (demand_shape[1:] - rho_D * demand_shape[:-1])
        xi[:, 1:] = demand_profiles[:, 1:] - rho_D * demand_profiles[:, :-1] - ref
    return xi


def _wind_innovations(
    wind_profiles: np.ndarray,
    wind_shape: np.ndarray,
    mu_W: float,
    rho_W: float,
    P_W_max: float,
) -> np.ndarray:
    """Whitened wind innovations (N, T).  Expected ~ N(0, (P_W_max*sigma_W)^2)."""
    N, T = wind_profiles.shape
    xi = np.zeros((N, T), dtype=float)
    xi[:, 0] = wind_profiles[:, 0] - P_W_max * mu_W * wind_shape[0]
    if T > 1:
        ref = P_W_max * mu_W * (wind_shape[1:] - rho_W * wind_shape[:-1])
        xi[:, 1:] = wind_profiles[:, 1:] - rho_W * wind_profiles[:, :-1] - ref
    return xi


def _demand_level_dev(
    demand_profiles: np.ndarray,
    demand_shape: np.ndarray,
    mu_D: float,
    D_ref: float,
) -> np.ndarray:
    """Level deviation from stationary reference (N, T).  Expected std = D_ref*sigma_bar_D."""
    ref = D_ref * mu_D * demand_shape[np.newaxis, :]
    return demand_profiles - ref


def _wind_level_dev(
    wind_profiles: np.ndarray,
    wind_shape: np.ndarray,
    mu_W: float,
    cap: float,
) -> np.ndarray:
    """Wind level deviation from stationary reference (N, T).  Expected std = cap*sigma_bar_W."""
    ref = cap * mu_W * wind_shape[np.newaxis, :]
    return wind_profiles - ref


def _rejection_rate(deviations: np.ndarray, sigma: float, kappa: float) -> float:
    """Fraction of trajectories where any time step violates the kappa*sigma tube."""
    return float(np.mean(np.any(np.abs(deviations) > kappa * sigma, axis=1)))


