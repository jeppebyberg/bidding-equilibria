def check_fleet_stats(
    fleet_dev: np.ndarray,
    cap_rms_sigma_bar_W: float,
    sum_caps_sigma_bar_W: float,
) -> None:
    """Report fleet empirical std vs. independence-based and per-gen-sum scalings."""
    std_emp = float(np.std(fleet_dev.flatten()))
    ratio_rms = std_emp / cap_rms_sigma_bar_W if cap_rms_sigma_bar_W > 0 else float("nan")
    ratio_sum = std_emp / sum_caps_sigma_bar_W if sum_caps_sigma_bar_W > 0 else float("nan")
    print(f"\n  Fleet level deviation std:")
    print(f"    empirical std          = {std_emp:.4g}")
    print(f"    cap_rms * sigma_bar_W  = {cap_rms_sigma_bar_W:.4g}  (correct, independence-based)")
    print(f"    sum_caps * sigma_bar_W = {sum_caps_sigma_bar_W:.4g}  (loose, per-gen-sum scaling)")
    print(f"    emp / cap_rms          = {ratio_rms:.4f}  (should be ~1.0)")
    print(f"    emp / sum_caps         = {ratio_sum:.4f}  (sqrt(N) gap visible for N > 1)")


