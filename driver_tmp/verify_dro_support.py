# Check 3 — sawtooth
# ---------------------------------------------------------------------------


def check_sawtooth(
    demand_shape: np.ndarray,
    wind_shape: np.ndarray,
    D_ref: float,
    mu_D: float,
    sigma_D: float,
    rho_D: float,
    P_W_max: float,
    mu_W: float,
    sigma_W: float,
    rho_W: float,
    total_capacity: float,
    T: int,
    chosen_coverage: float,
) -> None:
    kappa = _ar1_kappa(T, chosen_coverage)
    thr_D = kappa * D_ref * sigma_D
    thr_W = kappa * P_W_max * sigma_W

    D_saw = np.where(np.arange(T) % 2 == 0, total_capacity, 0.0)
    xi_D = _demand_innovations(D_saw[np.newaxis, :], demand_shape, mu_D, rho_D, D_ref)[0]
    d_viol = bool(np.any(np.abs(xi_D) > thr_D))

    W_saw = np.where(np.arange(T) % 2 == 0, P_W_max, 0.0)
    xi_W = _wind_innovations(W_saw[np.newaxis, :], wind_shape, mu_W, rho_W, P_W_max)[0]
    w_viol = bool(np.any(np.abs(xi_W) > thr_W))

    print(f"\n  Sawtooth adversarial test (coverage={chosen_coverage}, kappa={kappa:.4f}):")
    print(f"    Demand: max|xi|={np.max(np.abs(xi_D)):.4g}  threshold={thr_D:.4g}  "
          f"REJECTED={d_viol}")
    print(f"    Wind:   max|xi|={np.max(np.abs(xi_W)):.4g}  threshold={thr_W:.4g}  "
          f"REJECTED={w_viol}")
    if not d_viol or not w_viol:
        print("  WARNING: sawtooth NOT fully rejected — coherence should move into the "
              "transport cost.")
    else:
        print("  OK: sawtooth correctly rejected by the AR(1) tube.")


# ---------------------------------------------------------------------------
# Check 4 — innovation-stack and fleet-stack corner tests
# ---------------------------------------------------------------------------


def check_innovation_stack(
    demand_shape: np.ndarray,
    D_ref: float,
    mu_D: float,
    rho_D: float,
    T: int,
    kappa_innov: float,
    kappa_lvl: float,
    sigma_D_innov: float,
    sigma_bar_D: float,
) -> None:
    """Path where every AR(1) innovation equals +kappa_innov*sigma.

    Innovation tube must accept it; level band must reject it.
    """
    # Use (1-1e-9) so the path sits definitively inside the tube despite FP accumulation.
    innov_step = (1.0 - 1e-9) * kappa_innov * sigma_D_innov
    D_stack = np.zeros(T)
    D_stack[0] = D_ref * mu_D * demand_shape[0] + innov_step
    for t in range(1, T):
        ref_inc = D_ref * mu_D * (demand_shape[t] - rho_D * demand_shape[t - 1])
        D_stack[t] = rho_D * D_stack[t - 1] + ref_inc + innov_step

    xi = _demand_innovations(D_stack[np.newaxis, :], demand_shape, mu_D, rho_D, D_ref)[0]
    lvl_dev = _demand_level_dev(D_stack[np.newaxis, :], demand_shape, mu_D, D_ref)[0]

    innov_thr = kappa_innov * sigma_D_innov
    lvl_thr = kappa_lvl * sigma_bar_D

    innov_rejected = bool(np.any(np.abs(xi) > innov_thr))
    lvl_rejected = bool(np.any(np.abs(lvl_dev) > lvl_thr))

    print(f"\n  Innovation-stack test (all innovations at +kappa_innov edge):")
    print(f"    kappa_innov={kappa_innov:.4f}  kappa_lvl={kappa_lvl:.4f}")
    print(f"    Innovation tube: max|xi|={np.max(np.abs(xi)):.4g}  thr={innov_thr:.4g}  "
          f"REJECTED={innov_rejected}  (expected False)")
    print(f"    Level band:      max|dev|={np.max(np.abs(lvl_dev)):.4g}  thr={lvl_thr:.4g}  "
          f"REJECTED={lvl_rejected}  (expected True)")
    if innov_rejected:
        print("  WARNING: stacked path rejected by the innovation tube (unexpected).")
    if not lvl_rejected:
        print("  WARNING: level band failed to reject stacked path — consider raising "
              "CHOSEN_LEVEL_COVERAGE.")
    if not innov_rejected and lvl_rejected:
        print("  OK: level band closes the corner the innovation tube leaves open.")


def check_fleet_stack(
    wind_shape: np.ndarray,
    mu_W: float,
    sigma_W: float,
    rho_W: float,
    wind_gen_data: dict[str, tuple[np.ndarray, float]],
    T: int,
    kappa_innov: float,
    kappa_fleet: float,
    cap_rms_sigma_bar_W: float,
) -> None:
    """Every wind generator simultaneously at its lower innovation edge.

    Per-generator innovation tubes must accept; fleet band must reject.
    """
    fleet_stack = np.zeros(T)
    sum_caps = 0.0
    per_gen_info: list[tuple[str, float, bool]] = []

    for name, (_, cap_i) in wind_gen_data.items():
        innov_step = -(1.0 - 1e-9) * kappa_innov * cap_i * sigma_W  # just inside lower edge
        P_stack = np.zeros(T)
        P_stack[0] = cap_i * mu_W * wind_shape[0] + innov_step
        for t in range(1, T):
            ref_inc = cap_i * mu_W * (wind_shape[t] - rho_W * wind_shape[t - 1])
            P_stack[t] = rho_W * P_stack[t - 1] + ref_inc + innov_step

        xi = _wind_innovations(P_stack[np.newaxis, :], wind_shape, mu_W, rho_W, cap_i)[0]
        innov_thr = kappa_innov * cap_i * sigma_W
        gen_rejected = bool(np.any(np.abs(xi) > innov_thr))
        ratio = float(np.max(np.abs(xi)) / innov_thr) if innov_thr > 0 else float("nan")
        per_gen_info.append((name, ratio, gen_rejected))
        fleet_stack += P_stack
        sum_caps += cap_i

    fleet_dev = fleet_stack - sum_caps * mu_W * wind_shape
    lvl_thr = kappa_fleet * cap_rms_sigma_bar_W
    fleet_rejected = bool(np.any(np.abs(fleet_dev) > lvl_thr))
    per_gen_accepted = not any(rej for _, _, rej in per_gen_info)

    print(f"\n  Fleet-stack test (all generators at lower innovation edge simultaneously):")
    print(f"    kappa_innov={kappa_innov:.4f}  kappa_fleet={kappa_fleet:.4f}")
    for name, ratio, gen_rej in per_gen_info:
        print(f"    {name}: max|xi|/thr={ratio:.4f}  REJECTED={gen_rej}  (expected False)")
    print(f"    Fleet band: max|dev|={np.max(np.abs(fleet_dev)):.4g}  thr={lvl_thr:.4g}  "
          f"REJECTED={fleet_rejected}  (expected True)")
    if not per_gen_accepted:
        print("  WARNING: fleet-stack path rejected by a per-gen innovation tube (unexpected).")
    if not fleet_rejected:
        print("  WARNING: fleet band failed to reject stacked fleet path — consider raising "
              "CHOSEN_FLEET_COVERAGE.")
    if per_gen_accepted and fleet_rejected:
        print("  OK: fleet band closes the corner individual tubes leave open.")


