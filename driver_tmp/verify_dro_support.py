def plot_support_set_bounds(
    demand_profiles: np.ndarray,
    wind_gen_data: dict[str, tuple[np.ndarray, float]],
    demand_shape: np.ndarray,
    wind_shape: np.ndarray,
    D_ref: float,
    mu_D: float,
    sigma_D: float,
    rho_D: float,
    mu_W: float,
    sigma_W: float,
    rho_W: float,
    T: int,
    kappa_ar1: float,
    kappa_lvl: float,
    kappa_fleet: float,
    output_dir: Path,
    source_label: str,
    max_overlay: int = 40,
) -> None:
    """Plot demand and per-generator wind support set bounds.

    Panels show:
      - Sample trajectories (grey, semi-transparent)
      - Innovation-tube reachable envelope: the set of levels reachable if every
        innovation sits at its maximum allowed edge — a growing "trumpet".
      - Stationary level / fleet band: constant-width channel around the reference.
      - Combined support U: intersection of the two (what the MILP actually allows).
      - Deterministic reference trajectory.
      - Worst-case stacked path: innovations always at one edge — inside the tube
        but exits the level/fleet band, illustrating why the new constraints matter.
    """
    t = np.arange(T)
    sigma_D_innov = D_ref * sigma_D
    sigma_bar_D = D_ref * sigma_D / np.sqrt(1.0 - rho_D ** 2)
    sigma_bar_W_scalar = sigma_W / np.sqrt(1.0 - rho_W ** 2)

    caps = [cap for _, (_, cap) in wind_gen_data.items()]
    sum_caps = float(sum(caps))
    cap_rms = float(np.sqrt(sum(c ** 2 for c in caps)))

    # ------------------------------------------------------------------
    # Demand: reference, innovation-tube envelope, level band
    # ------------------------------------------------------------------
    demand_ref = D_ref * mu_D * demand_shape  # (T,)

    # Reachable envelope: recursively propagate ± kappa * sigma at each step.
    # At t=0: cold-start band (same kappa, innovation std).
    # At t≥1: D[t] = rho*D[t-1] + ref_inc + kappa*sigma  (upper),
    #                rho*D[t-1] + ref_inc - kappa*sigma  (lower).
    innov_lo_D = np.zeros(T)
    innov_hi_D = np.zeros(T)
    innov_lo_D[0] = demand_ref[0] - kappa_ar1 * sigma_D_innov
    innov_hi_D[0] = demand_ref[0] + kappa_ar1 * sigma_D_innov
    for s in range(1, T):
        ref_inc = D_ref * mu_D * (demand_shape[s] - rho_D * demand_shape[s - 1])
        innov_lo_D[s] = rho_D * innov_lo_D[s - 1] + ref_inc - kappa_ar1 * sigma_D_innov
        innov_hi_D[s] = rho_D * innov_hi_D[s - 1] + ref_inc + kappa_ar1 * sigma_D_innov

    level_lo_D = demand_ref - kappa_lvl * sigma_bar_D
    level_hi_D = demand_ref + kappa_lvl * sigma_bar_D

    # Combined: intersection + D ≥ 0 physical floor.
    combined_lo_D = np.maximum(np.maximum(innov_lo_D, level_lo_D), 0.0)
    combined_hi_D = np.minimum(innov_hi_D, level_hi_D)

    # Worst-case stacked demand path (innovations at upper edge, just inside tube).
    step_D = (1.0 - 1e-9) * kappa_ar1 * sigma_D_innov
    D_stack = np.empty(T)
    D_stack[0] = demand_ref[0] + step_D
    for s in range(1, T):
        ref_inc = D_ref * mu_D * (demand_shape[s] - rho_D * demand_shape[s - 1])
        D_stack[s] = rho_D * D_stack[s - 1] + ref_inc + step_D

    # ------------------------------------------------------------------
    # Wind fleet: reference, innovation-tube envelope, fleet band
    # ------------------------------------------------------------------
    fleet_ref = sum_caps * mu_W * wind_shape  # (T,)

    # Reachable fleet envelope: all generators simultaneously at ± edge.
    # Per-gen: |xi_i| ≤ kappa * cap_i * sigma_W.  Sum: ≤ kappa * sum_caps * sigma_W.
    fleet_innov_lo = np.zeros(T)
    fleet_innov_hi = np.zeros(T)
    fleet_innov_lo[0] = fleet_ref[0] - kappa_ar1 * sum_caps * sigma_W
    fleet_innov_hi[0] = fleet_ref[0] + kappa_ar1 * sum_caps * sigma_W
    for s in range(1, T):
        ref_inc = sum_caps * mu_W * (wind_shape[s] - rho_W * wind_shape[s - 1])
        fleet_innov_lo[s] = rho_W * fleet_innov_lo[s - 1] + ref_inc - kappa_ar1 * sum_caps * sigma_W
        fleet_innov_hi[s] = rho_W * fleet_innov_hi[s - 1] + ref_inc + kappa_ar1 * sum_caps * sigma_W

    # Fleet level band uses cap_rms (independence-scaled), not sum_caps.
    fleet_level_lo = fleet_ref - kappa_fleet * cap_rms * sigma_bar_W_scalar
    fleet_level_hi = fleet_ref + kappa_fleet * cap_rms * sigma_bar_W_scalar

    # Combined: intersection + fleet ∈ [0, sum_caps].
    combined_fleet_lo = np.maximum(np.maximum(fleet_innov_lo, fleet_level_lo), 0.0)
    combined_fleet_hi = np.minimum(np.minimum(fleet_innov_hi, fleet_level_hi), sum_caps)

    # Worst-case fleet stack: all generators at lower innovation edge simultaneously.
    step_W = (1.0 - 1e-9) * kappa_ar1
    fleet_stack = np.zeros(T)
    for _, (_, cap_i) in wind_gen_data.items():
        P_i = np.empty(T)
        P_i[0] = cap_i * mu_W * wind_shape[0] - step_W * cap_i * sigma_W
        for s in range(1, T):
            ref_inc = cap_i * mu_W * (wind_shape[s] - rho_W * wind_shape[s - 1])
            P_i[s] = rho_W * P_i[s - 1] + ref_inc - step_W * cap_i * sigma_W
        fleet_stack += P_i

    # Sample fleet sums for overlay.
    fleet_profiles_overlay: np.ndarray = sum(  # type: ignore[assignment]
        wp for wp, _ in wind_gen_data.values()
    )

    # ------------------------------------------------------------------
    # Plot
    # ------------------------------------------------------------------
    n_overlay = min(max_overlay, len(demand_profiles))
    n_panels = 1 + len(wind_gen_data)
    fig_height = max(5.0, 4.0 * n_panels)
    fig, axes_raw = plt.subplots(n_panels, 1, figsize=(10, fig_height), sharex=True)
    axes = np.atleast_1d(axes_raw)

    _ORANGE = "#E8820C"
    _GREEN = "#2CA02C"
    _PURPLE = "#7B2D8B"
    _BLUE = "#1F77B4"
    _RED = "#D62728"

    wind_plot_specs = []
    for idx, (gen_name, (wind_profiles, cap_i)) in enumerate(wind_gen_data.items(), start=1):
        wind_ref = cap_i * mu_W * wind_shape
        sigma_W_innov = cap_i * sigma_W
        sigma_bar_W = cap_i * sigma_bar_W_scalar

        innov_lo_W = np.zeros(T)
        innov_hi_W = np.zeros(T)
        innov_lo_W[0] = wind_ref[0] - kappa_ar1 * sigma_W_innov
        innov_hi_W[0] = wind_ref[0] + kappa_ar1 * sigma_W_innov
        for s in range(1, T):
            ref_inc = cap_i * mu_W * (wind_shape[s] - rho_W * wind_shape[s - 1])
            innov_lo_W[s] = rho_W * innov_lo_W[s - 1] + ref_inc - kappa_ar1 * sigma_W_innov
            innov_hi_W[s] = rho_W * innov_hi_W[s - 1] + ref_inc + kappa_ar1 * sigma_W_innov

        level_lo_W = wind_ref - kappa_lvl * sigma_bar_W
        level_hi_W = wind_ref + kappa_lvl * sigma_bar_W
        combined_lo_W = np.maximum(np.maximum(innov_lo_W, level_lo_W), 0.0)
        combined_hi_W = np.minimum(np.minimum(innov_hi_W, level_hi_W), cap_i)

        step_W = (1.0 - 1e-9) * kappa_ar1 * sigma_W_innov
        wind_stack = np.empty(T)
        wind_stack[0] = wind_ref[0] - step_W
        for s in range(1, T):
            ref_inc = cap_i * mu_W * (wind_shape[s] - rho_W * wind_shape[s - 1])
            wind_stack[s] = rho_W * wind_stack[s - 1] + ref_inc - step_W

        wind_plot_specs.append(
            (
                axes[idx], wind_ref,
                innov_lo_W, innov_hi_W,
                level_lo_W, level_hi_W,
                combined_lo_W, combined_hi_W,
                wind_stack,
                wind_profiles[:n_overlay],
                cap_i,
                f"Wind {gen_name}  P[t]  (MW)",
                f"Wind {gen_name} - support set bounds  [{source_label}]",
                f"AR(1) tube envelope  (kappa={kappa_ar1:.2f}, cap*sigma_inn)",
                f"Level band  (kappa={kappa_lvl:.2f}, cap*sigma_bar)",
            )
        )

    for ax, ref, innov_lo, innov_hi, lvl_lo, lvl_hi, comb_lo, comb_hi, stack, overlays, \
            phys_hi, ylabel, title, innov_lbl, lvl_lbl in [
        (
            axes[0], demand_ref,
            innov_lo_D, innov_hi_D,
            level_lo_D, level_hi_D,
            combined_lo_D, combined_hi_D,
            D_stack,
            demand_profiles[:n_overlay],
            None,
            "Demand  D[t]  (MW)",
            f"Demand — support set bounds  [{source_label}]",
            f"AR(1) tube envelope  (κ={kappa_ar1:.2f}, σ_inn)",
            f"Level band  (κ={kappa_lvl:.2f}, σ̄)",
        ),
        (
            axes[1], fleet_ref,
            fleet_innov_lo, fleet_innov_hi,
            fleet_level_lo, fleet_level_hi,
            combined_fleet_lo, combined_fleet_hi,
            fleet_stack,
            fleet_profiles_overlay[:n_overlay],
            sum_caps,
            "Wind fleet  ΣP[t]  (MW)",
            f"Wind fleet — support set bounds  [{source_label}]",
            f"AR(1) tube envelope  (κ={kappa_ar1:.2f}, Σcap·σ_inn)",
            f"Fleet band  (κ={kappa_fleet:.2f}, cap_rms·σ̄)",
        ),
    ][:1] + wind_plot_specs:
        # Sample draws
        for row in overlays:
            ax.plot(t, row, color="silver", lw=0.7, alpha=0.5, zorder=1)

        # Innovation-tube reachable region
        ax.fill_between(t, innov_lo, innov_hi, color=_ORANGE, alpha=0.18,
                        label=innov_lbl, zorder=2)
        ax.plot(t, innov_lo, color=_ORANGE, lw=1.2, ls="--", zorder=3)
        ax.plot(t, innov_hi, color=_ORANGE, lw=1.2, ls="--", zorder=3)

        # Level / fleet band
        ax.fill_between(t, lvl_lo, lvl_hi, color=_GREEN, alpha=0.18,
                        label=lvl_lbl, zorder=2)
        ax.plot(t, lvl_lo, color=_GREEN, lw=1.5, ls="-.", zorder=4)
        ax.plot(t, lvl_hi, color=_GREEN, lw=1.5, ls="-.", zorder=4)

        # Physical limits
        ax.axhline(0.0, color="black", lw=0.9, ls=":", zorder=4)
        if phys_hi is not None:
            ax.axhline(phys_hi, color="black", lw=0.9, ls=":",
                       label=f"Physical cap ({phys_hi:.0f} MW)", zorder=4)

        # Combined support set (intersection)
        ax.plot(t, comb_lo, color=_PURPLE, lw=2.2, label="Combined support U", zorder=5)
        ax.plot(t, comb_hi, color=_PURPLE, lw=2.2, zorder=5)

        # Deterministic reference
        ax.plot(t, ref, color=_BLUE, lw=2.5, label="Reference (det.)", zorder=6)

        # Edge path
        ax.plot(t, stack, color=_RED, lw=2.0, ls="--",
                label="Edge path (inside tube, may exit band)", zorder=6)

        ax.set_ylabel(ylabel)
        ax.set_title(title)
        ax.legend(loc="upper right", fontsize=8.5, framealpha=0.9)
        ax.grid(True, alpha=0.25)
        ax.set_xticks(t)

    axes[-1].set_xlabel("Time step  t")
    fig.tight_layout()
    slug = source_label.lower().replace(" ", "_").replace("(", "").replace(")", "")
    path = output_dir / f"support_set_bounds_by_generator_{slug}.png"
    fig.savefig(path, dpi=180, bbox_inches="tight")
    plt.close(fig)
    print(f"  Support set bounds plot saved: {path}")


