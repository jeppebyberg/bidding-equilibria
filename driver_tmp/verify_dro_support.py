def check_innovations(
    innovations: np.ndarray,
    sigma_innov: float,
    label: str,
    output_dir: Path,
) -> None:
    xi = innovations.flatten()
    mean = float(np.mean(xi))
    std = float(np.std(xi))
    skew = float(np.mean(((xi - mean) / std) ** 3)) if std > 0 else float("nan")

    print(f"\n  {label}:")
    print(f"    n            = {len(xi)}")
    print(f"    mean         = {mean:.4g}  (expected 0)")
    print(f"    std          = {std:.4g}  (expected {sigma_innov:.4g})")
    print(f"    std/expected = {std / sigma_innov:.4f}  (should be ~1.0)")
    print(f"    skewness     = {skew:.4f}  (expected ~0; clipping shifts wind)")

    fig, ax = plt.subplots(figsize=(7.5, 4.5))
    bins = min(80, max(30, len(xi) // 40))
    ax.hist(xi, bins=bins, density=True, alpha=0.6, label="draws")
    x_grid = np.linspace(xi.min(), xi.max(), 400)
    ax.plot(x_grid, _norm.pdf(x_grid, 0.0, sigma_innov), "r-", lw=2,
            label=f"N(0, {sigma_innov:.3g}²)")
    ax.set_xlabel("Whitened innovation / level deviation")
    ax.set_ylabel("Density")
    ax.set_title(label)
    ax.legend()
    ax.grid(True, alpha=0.25)
    fig.tight_layout()
    slug = label.lower().replace(" ", "_").replace("/", "_").replace("[", "").replace("]", "")
    path = output_dir / f"innovations_{slug}.png"
    fig.savefig(path, dpi=160, bbox_inches="tight")
    plt.close(fig)
    print(f"    Saved: {path}")


