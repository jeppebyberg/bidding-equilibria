REGIME_NAME = "normal"
HORIZON = 8
N_DRAWS = 2000          # fresh draws for statistical checks
VERIFY_SEED = 77777     # separate from training/DRO seeds
CHOSEN_COVERAGE = 0.99  # coverage intended for DROWassersteinSupportSet
OUTPUT_DIR = Path("results/verify_dro_support")
COVERAGE_GRID = [0.90, 0.95, 0.99, 0.999, 0.9999]
# Path to the scenarios already generated by the DRO pipeline.
