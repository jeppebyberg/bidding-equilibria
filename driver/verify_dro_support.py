"""Verification script for DROWassersteinSupportSet.

Three checks, run on two scenario sources:
  - EXISTING: the scenarios already generated by the DRO pipeline
    (constrained to the old DROPoASupportSet).  These should always pass
    the new AR(1)-only tube because the new kappa is larger than the old one.
  - FRESH: N_DRAWS unconstrained draws from the regime distribution.
    Use these to pick the smallest kappa that gives 0% rejection on raw draws.

Check 1 — Whitened-innovation histogram
  xi_0 = D[0] - D_ref*mu_D*shape[0]
  xi_t = D[t] - rho_D*D[t-1] - D_ref*mu_D*(shape[t] - rho_D*shape[t-1])  for t >= 1
  Expected: N(0, (D_ref*sigma_D)^2).  Same formula for wind, with P_W_max*sigma_W.

Check 2 — Rejection-rate sweep
  Fraction of trajectories where any time step violates the AR(1) tube,
  scanned over a grid of coverage values.  Chosen coverage should give 0%.

Check 3 — Sawtooth adversarial test
  An alternating max/min path has innovations ~ rho * physical_range >> tube width.
  The tube should always reject it; if not, coherence must move to the transport cost.

Usage:
    .venv/Scripts/python.exe driver/verify_dro_support.py
"""
